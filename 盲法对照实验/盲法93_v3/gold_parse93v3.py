def preprocess(body):
    body = body.replace('耳膽石点','耳胆点').replace('双耳肾点','耳肾点').replace('右耳肾点','耳肾点')
    body = body.replace('埋耳针<胆>','耳胆点').replace('埋耳针(眼)','耳眼点')
    body = body.replace('耳穴肝点','耳肝点')
    body = body.replace('第十椎压痛点','第十椎压痛点').replace('第十椎','第十椎压痛点')
    body = body.replace('腿腰点','腰腿点')
    body = re.sub(r'(?<!耳)肾石点','肾结石点', body)
    body = body.replace('开四关','合谷 太冲')
    return body

def extract_tokens(text):
    lines = [ln for ln in text.splitlines() if not re.match(r'^\s*doc\(', ln)]
    body = t2s(' '.join(lines))
    body = preprocess(body)
    tokens = []
    i, n = 0, len(body)
    while i < n:
        matched = None
        for name in CANON:
            L = len(name)
            if body[i:i+L] == name:
                matched = name; break
        if matched:
            tokens.append(matched); i += len(matched)
        else:
            i += 1
    out = [ALIAS.get(t,t) for t in tokens]
    final = []
    for t in out:
        if '透' in t:
            a,b = t.split('透',1); final.append(a); final.append(b)
        else:
            final.append(t)
    seen=set(); uniq=[]
    for t in final:
        if t not in seen: seen.add(t); uniq.append(t)
    return uniq

def expand_gold_tokens(tokens):
    members=set(); log=[]
    for t in tokens:
        if t=='膝五针':
            for ep in ['鹤顶','内膝眼','外膝眼','阴陵泉']: members.add(ep)
            members.add('膝五针'); log.append('膝五针->{鹤顶,内膝眼,外膝眼,阴陵泉}')
        elif t=='三皇穴':
            for ep in ['阴陵泉','地机','三阴交']: members.add(ep)
            members.add('三皇穴'); log.append('三皇穴->{阴陵泉,地机,三阴交}')
        else:
            members.add(t)
    return members, len(members), log

def expand_blind_unit(u):
    u=u.strip()
    u=u.replace('天应隔姜灸','天应').replace('灸关元','关元').replace('灸中脘','中脘').replace('灸天枢','天枢')
    u=u.replace('上星米粒灸','上星').replace('耳尖放血','耳尖').replace('委中放血','委中').replace('少商放血','少商').replace('商阳放血','商阳')
    u=u.replace('膀胱募','中极')
    if u=='心脏点': return {'耳心点'}
    if u=='耳针埋心的压痛点': return {'耳心点'}
    if '透' in u:
        a,b=u.split('透',1); return {a,b}
    if '+' in u:
        return set(p.strip() for p in u.split('+'))
    return {u}

