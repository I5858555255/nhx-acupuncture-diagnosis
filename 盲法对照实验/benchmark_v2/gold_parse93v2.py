# ---- 组穴 → 组成穴（统一 normalize_acupoints，不再保留父级组名）----
def expand_gold(tokens):
    """tokens → 规范 gold 穴集 + 展开日志（穴位级口径）。"""
    members = normalize_acupoints(tokens)
    # 展开日志：记录哪些 token 属于组穴展开（审计用途）
    log = []
    for t in tokens:
        if t in ('膝五针', '三皇穴', '开四关'):
            comp = ['鹤顶','内膝眼','外膝眼','阴陵泉'] if t=='膝五针' else (['阴陵泉','地机','三阴交'] if t=='三皇穴' else ['合谷','太冲'])
            log.append(f"{t}->{{{','.join(comp)}}}")
    return members, len(members), log


