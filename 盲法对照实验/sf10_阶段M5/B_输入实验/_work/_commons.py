def scan_text(text):
    """返回命中列表 [(kind, word, snippet)]。kind in {'穴名','处方词'}"""
    hits = []
    if not text:
        return hits
    for p in ACUPOINTS:
        if p and p in text:
            hits.append(("穴名", p, text))
    for w in RX_WORDS:
        if w in text:
            hits.append(("处方词", w, text))
    return hits

