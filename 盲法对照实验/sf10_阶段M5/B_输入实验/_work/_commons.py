def field_frag(d, key):
    """取字段文本片段：dict{片段,定位} 或纯字符串标缺失，统一返回字符串。"""
    v = d.get(key)
    if isinstance(v, dict):
        return v.get("片段", "") or ""
    if isinstance(v, str):
        return v  # 通常是 '原文未记录'
    return ""

def is_missing(d, key):
    v = d.get(key)
    if isinstance(v, str):
        return v.strip() == MISSING_MARK
    if isinstance(v, dict):
        return (v.get("片段") or "").strip() == MISSING_MARK
    return False

