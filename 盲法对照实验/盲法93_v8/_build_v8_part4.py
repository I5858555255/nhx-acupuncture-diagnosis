# ⑫ 逐穴出处标注：每个主穴(透/+组分)须在推理要点出现且附近有出处标记
def tokens(x):
    out=[]
    if "透" in x: out+=x.split("透")
    elif "+" in x: out+=x.split("+")
    else: out.append(x)
    return out
